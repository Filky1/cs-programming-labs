price=float(input("Введите стоимость билета:"))
year=int(input("Введите возраст:"))
if price<0 or 0>=year>=120: print('Ошибка')
if 0<=year<=5: print('Стоимость: 0.00 руб')
if 6<=year<=17: print(f'Стоимость: {price*0.5:.2f} руб')
if 18<=year<=59: print(f'Стоимость: {price:.2f} руб')
if 60<=year<=120: print(f'Стоимость: {price*0.7:.2f} руб')
